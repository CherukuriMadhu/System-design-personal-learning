class Bird:

    def sound(self):
        print("Bird makes a sound")


class Parrot(Bird):

    def sound(self):
        print("Parrot says Hello!")


class Crow(Bird):

    def sound(self):
        print("Crow says Caw Caw")


class Peacock(Bird):

    def sound(self):
        print("Peacock makes a loud call")